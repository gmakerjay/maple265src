let icon = require('constant/Icon');
// 只声明一次str，保留一个标题（避免重复声明）
let str = "\t\t\t\t\t#e#b[管理功能]#k#l\r\n";  // 保留需要的标题，删除重复声明

let list = [
    ["事件管理", "管理員測試/事件管理"],
    ["素材套裝", "管理員測試/素材套裝"],
	["屬性裝備", "管理員測試/屬性裝備"],
	["等級設置", "管理員測試/等級設置"],
	["地圖獎勵", "管理員測試/地圖獎勵"],
	["活動開放", "管理員測試/活動開放"],
	["拜師系統", "管理員測試/師徒系統"],
	["測試專用", "管理員測試/測試專用"],
	["傷害皮膚", "管理員測試/傷害皮膚"],
	["一鍵畢業裝", "管理員測試/一鍵畢業裝"],
	["一鍵掉落套", "管理員測試/一鍵掉落套"],
	["一鍵滿六核", "管理員測試/一鍵滿六核"],
	["一鍵滿神秘", "管理員測試/一鍵滿神秘"],
	["一鍵滿原初", "管理員測試/一鍵滿原初"],
	
	
];

// 循环拼接功能选项（每个选项单独一行）
for (let i = 0; i < list.length; i++) {
	str += (i % 4 === 0 && i > 0) ? "\r\n" : "";
  
    str += `#L${i}##k${list[i][0]}#l`;  // 拼接选项（带选择ID）
}

// 拼接“返回主菜单”选项
str += `\r\n\r\n\t\t\t#fs14##L999#${icon.common.返回[0]}返回主菜單#l`;

// 显示菜单（此时str已正确构建，无语法错误）
let selection = npc.askMenu(str);

// 处理选择（添加索引有效性判断）
if (selection === 999) {
    // 返回主菜单
    stage.runScript('expand/menu');
} else if (selection >= 0 && selection < list.length) {  // 判断是否为有效选项索引
    // 执行对应功能脚本（仅当索引有效时）
    stage.runScript("expand/menu/" + list[selection][1]);
} else {
    // 无效选择时提示（避免脚本报错）
    npc.say("无效选项，请重新选择！");
}