function start() {
    let str = `請選擇要分解的拼圖:\r\n`;
    for (let i = 20000; i <= 20023; i++) {
        let p1 = stage.getItemBySlot(10, i); 
            stage.showSystemMessage(p1 ) 
        if (p1 && info[p1.getItemId()]) {
            str += `#L${i}##v${p1.getItemId()}:i##z${p1.getItemId()}:i#\t位置:${i - 19999}#l\r\n`;
        }
    }
    let sel = npc.askMenu(str);
    let toDrop = stage.getItemBySlot(10, sel);
    let pId = toDrop.getItemId();
    str = `是否確定分解\r\n位置:${sel - 19999}  #v${pId}:i##z${pId}:i#，可獲得\r\n`;
    for (let i in info[pId]) {
        str += `#v${info[pId][i]}:i##z${info[pId][i]}:i#\r\n`;
    }
    if (npc.askYesNo(str) == 1) {
        stage.removeItemBySlot(10, sel);
        for (let i in info[pId]) {
            stage.gainItem(info[pId][i][0], info[pId][i][1]);
        }
        npc.say('分解成功');
        start();
    }
}

start();