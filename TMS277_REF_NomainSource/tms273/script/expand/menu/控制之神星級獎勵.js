function start() {

    while (true) {
        let say = "控制之神星級獎勵\r\n";
        say += "請選擇您要領取的層數獎勵:\r\n";
        for (let i = 1; i <= 40; i++) {
            if (i < 10) {
                say += "#L" + i + "#第0" + i + "層#l  ";
            } else {
                say += "#L" + i + "#第" + i + "層#l  ";
            }
        }
        say += `#L999#一鍵領取#l\r\n`;
        say += "\r\n "
        let sel = npc.askMenu(say);

        if (sel == 999) {
            let canList = [];
            let insertedKeys = {}; 

            for (let i = 1; i <= 40; i++) {
                let stars = getPlatformarStarByStage(i);
                for (let j = 1; j <= 3; j++) {
                    let key = "控制之神" + i + "層" + j + "星";
                    if (getEventValueWeek(key, true) === 0 && insertedKeys[key] !== true && stars >= j) {
                        canList.push([i, j]);
                        insertedKeys[key] = true;
                    }
                }
            }

            if (canList.length > 0) {
                for (let i = 0; i < canList.length; i++) {
                    let sel = canList[i][0];
                    let star = canList[i][1];
                    let key = "控制之神" + sel + "層" + star + "星";

                    setEventValue(key, 1, -1);
                    let rewards = everyFloor[sel - 1][star - 1];
                    for (let j = 0; j < rewards.length; j++) {
                        stage.gainItem(rewards[j][0], rewards[j][1]);
                    }

                    util.broadcastChatMsg(16, "【控制之神】 : 祝賀操作大神 " + stage.getCharacterName() + " 領取了 <控制之神" + sel + "層" + star + "星> 的豐厚獎勵！真讓人羨慕~");
                }
                npc.say("一鍵領取成功！");
            } else {
                npc.say("當前沒有可領取的獎勵!");
            }
            return;
        }

        say = "您選擇的是第" + sel + "層獎勵,當前層數您的星級為 " + getPlatformarStarByStage(sel) + " 星\r\n"
        say += "#b#L1# ★☆☆ 獎勵 " + (getEventValueWeek("控制之神" + sel + "層1星", true) > 0 ? "#r(已領取)" : "#g(未領取)") + "#l\r\n"
        say += "#b#L2# ★★☆ 獎勵 " + (getEventValueWeek("控制之神" + sel + "層2星", true) > 0 ? "#r(已領取)" : "#g(未領取)") + "#l\r\n"
        say += "#b#L3# ★★★ 獎勵 " + (getEventValueWeek("控制之神" + sel + "層3星", true) > 0 ? "#r(已領取)" : "#g(未領取)") + "#l\r\n"

        let star = npc.askMenu(say);

        say = "您選擇的是第" + sel + "層" + star + "星獎勵,當前層數您的星級為 " + getPlatformarStarByStage(sel) + " 星\r\n";
        say += "獎勵如下\r\n";
        for (let i = 0; i < everyFloor[sel - 1][star - 1].length; i++) {
            say += "#v" + everyFloor[sel - 1][star - 1][i][0] + "##z" + everyFloor[sel - 1][star - 1][i][0] + "# x " + everyFloor[sel - 1][star - 1][i][1] + "\r\n"
        }
        say += "是否領取？"
        let YN = npc.askYesNo(say);
        if (YN == 1) {
            if (getEventValueWeek("控制之神" + sel + "層" + star + "星", true) > 0) {
                npc.say("你已經領取過該獎勵！");
            } else if (getPlatformarStarByStage(sel) < star) {
                npc.say("你的星級不夠領取該獎勵！");
            } else if (stage.getFreeSlot(1) < everyFloor[sel - 1][star - 1].length || stage.getFreeSlot(2) < everyFloor[sel - 1][star - 1].length || stage.getFreeSlot(3) < everyFloor[sel - 1][star - 1].length || stage.getFreeSlot(4) < everyFloor[sel - 1][star - 1].length || stage.getFreeSlot(5) < everyFloor[sel - 1][star - 1].length) {
                npc.say("請將背包空餘出" + everyFloor[sel - 1][star - 1].length + "以上的空位置")
            } else {
                setEventValue("控制之神" + sel + "層" + star + "星", 1, -1);
                for (let i = 0; i < everyFloor[sel - 1][star - 1].length; i++) {
                    stage.gainItem(everyFloor[sel - 1][star - 1][i][0], everyFloor[sel - 1][star - 1][i][1]);
                }
                util.broadcastChatMsg(16, "【控制之神】 : 祝賀操作大神 " + stage.getCharacterName() + " 領取了 <控制之神" + sel + "層" + star + "星 的豐厚獎勵！真讓人羨慕~");

                npc.say("領取成功！")
            }
        }
    }

}

start();

function getPlatformarStarByStage(stage1) {
    return stage.getIntQuestRecordEx((stage1 - 1) + 18839, "cs");
}

//flag = true 查總的不重置
//flag = false 查當天的
function getEventValue(event1, flag) {
    if (flag) {
        var sql = "SELECT SUM(value) AS numbe FROM accounts_event WHERE accounts_id = " + stage.getAccountId() + " and event = '" + event1 + "' and world =" + 0 + " ";
    } else {
        var sql = "SELECT SUM(value) AS numbe FROM accounts_event WHERE accounts_id = " + stage.getAccountId() + " and event = '" + event1 + "' and world =" + 0 + " AND DATE(time) BETWEEN DATE(NOW() - INTERVAL WEEKDAY(NOW()) DAY) AND DATE(NOW() + INTERVAL (7 - WEEKDAY(NOW())) DAY) ";
    }
    var resultList = db.select(sql);
    var count = 0;
    for (var i = 0; i < resultList.length; i++) {
        var result = resultList[i];
        if (result == null) {
            break;
        }
        count = result.get("numbe");
        if (count == null) {
            count = 0;
        }
    }
    return parseInt(count);
}

// 周
function getEventValueWeek(event1) {
    var sql = "SELECT SUM(value) AS numbe FROM zz_xr_event WHERE accounts_id = " + stage.getAccountId() + " and event = '" + event1 + "' and world =" + 0 + " AND DATE(time) BETWEEN DATE(NOW() - INTERVAL WEEKDAY(NOW()) DAY) AND DATE(NOW() + INTERVAL (7 - WEEKDAY(NOW())) DAY) ";
    var resultList = db.select(sql);
    var count = 0;
    for (var i = 0; i < resultList.length; i++) {
        var result = resultList[i];
        if (result == null) {
            break;
        }
        count = result.get("numbe");
        if (count == null) {
            count = 0;
        }
    }
    return parseInt(count);
}

function getEventValueWeekList() {
    var sql = "SELECT * FROM zz_xr_event WHERE accounts_id = " + stage.getAccountId() + " and event like '控制之神%星' and world =" + 0 + " AND DATE(time) BETWEEN DATE(NOW() - INTERVAL WEEKDAY(NOW()) DAY) AND DATE(NOW() + INTERVAL (7 - WEEKDAY(NOW())) DAY) ";
    var resultList = db.select(sql);
    let res = [];
    for (let i in resultList) {
        res.push(resultList[i].get('event'));
    }
    return res;
}

function setEventValue(event1, value1) {
    var sql = "INSERT INTO zz_xr_event(accounts_id, world, `event`,`value`,time) VALUES(" + stage.getAccountId() + "," + 0 + ",'" + event1 + "'," + value1 + ",now())";
    db.insert(sql);
}

