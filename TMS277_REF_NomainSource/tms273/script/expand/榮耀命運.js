function extractValue(probability) {
    var totalWeight = 0;
    for (var i = 0; i < probability.length; i++) {
        totalWeight += probability[i].weight;
    }
    var randomValue = Math.random() * totalWeight;
    var cumulativeWeight = 0;
    for (var i = 0; i < probability.length; i++) {
        cumulativeWeight += probability[i].weight;
        if (randomValue <= cumulativeWeight) {
            return probability[i].value;
        }
    }
    return probability[probability.length - 1].value;
}

