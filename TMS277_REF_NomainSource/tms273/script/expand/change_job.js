function execute() {
    var flag = false;
    var text = "請選擇您要轉職的職業：\r\n";
    var subjob = stage.getSubJob();
    for (var i = 0; i < jobData.length; i++) {
        if (subjob == 1 && stage.getJob() == jobData[i][2] && jobData[i][4] == 1) {
            text += "#L" + i + "#" + jobData[i][0] + "#l#k\r\n";
            flag = true;
        } else if (subjob == 2 && stage.getJob() == jobData[i][2] && jobData[i][4] == 2) {
            text += "#L" + i + "#" + jobData[i][0] + "#l#k\r\n";
            flag = true;
        } else if (stage.getJob() == jobData[i][2] && (null == jobData[i][4] ? 0 : jobData[i][4]) == subjob) {
            text += "#b#L" + i + "#" + jobData[i][0] + "#l#k\r\n";
            flag = true;
        }
    }
    if (flag) {
        let sel = npc.askMenu(text);
        let ret = npc.askYesNo("您是否要轉職為:#b" + jobData[sel][0] + "#l#k。");
        if (ret == 1) {
            if (stage.getLevel() < jobData[sel][3]) {
                npc.next().say("對不起,您的等級不足#e#r" + jobData[sel][3] + "級#k#n。");
            } else {
                stage.setJob(jobData[sel][1]);
                switch (jobData[sel][1]) {
                    case 3600:/* 傑諾 */
                        stage.equipped(-10, 1353001);
                        break;
                    case 3610:
                        stage.equipped(-10, 1353002);
                        break;
                    case 3611:
                        stage.equipped(-10, 1353003);
                        break;
                    case 3612:
                        stage.equipped(-10, 1353004);
                        break;
                    case 6500:/* 天使 */
                        stage.equipped(-10, 1352601);
                        break;
                    case 6510:
                        stage.equipped(-10, 1352602);
                        break;
                    case 6511:
                        stage.equipped(-10, 1352603);
                        break;
                    case 6512:
                        stage.equipped(-10, 1352604);
                        break;
                    case 6100:/* 狂龍 */
                        stage.equipped(-10, 1352500);
                        break;
                    case 6110:
                        stage.equipped(-10, 1352501);
                        break;
                    case 6111:
                        stage.equipped(-10, 1352502);
                        break;
                    case 6112:
                        stage.equipped(-10, 1352503);
                        break;
                }

                stage.gainItem(2431304, 1);
                execute();
            }
        }
    } else {
        if (!stage.isQuestCompleted(1465)) {
            if (stage.getLevel() >= 200) {
                if (npc.meFlip().askYesNo("恭喜您!勇士!你現在可以進行 5 轉!") == 1) {
                    stage.completeQuest(1465);
                    stage.completeQuest(34478);
                    stage.gainItem(2435902, 300);
                    stage.updateQuestRecordEx(1477, "count", 1000);
                    npc.meFlip().say("轉職成功!獲得 1000 核心 300 核心寶石");
                    execute();
                    return;
                }
            } else {
                npc.meFlip().say("抱歉..200級才可以5轉!");
                return;
            }
        } else if (!stage.isQuestCompleted(1488)) {
            if (stage.getLevel() >= 260) {
                if (npc.meFlip().askYesNo("恭喜您!勇士!你現在可以進行 6 轉!") == 1) {
                    stage.completeQuest(1488);
                    stage.startQuest(1489);
                    for (let i = 38601; i <= 38625; i++) {
                        stage.completeQuest(i);
                    }
                    npc.meFlip().say("恭喜!六轉成功!"); 
                    return;
                }
            } else {
                npc.meFlip().say("抱歉..260級才可以6轉!");
                return;
            }
        }
        npc.next().say("對不起,你現在不能轉職。");
    }
}